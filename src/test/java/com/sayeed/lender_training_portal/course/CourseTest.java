package com.sayeed.lender_training_portal.course;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.assertj.core.api.Assertions.tuple;

import java.time.Instant;

import org.junit.jupiter.api.Test;
import org.springframework.test.util.ReflectionTestUtils;

import com.sayeed.lender_training_portal.common.BusinessRuleException;
import com.sayeed.lender_training_portal.user.AppUser;
import com.sayeed.lender_training_portal.user.Role;

/**
 * Pure domain tests: no Spring, no database, so they run in milliseconds. They pin the business rules
 * that live inside the entity itself.
 */
class CourseTest {

    private static final Instant T0 = Instant.parse("2026-01-01T09:00:00Z");

    @Test
    void addModule_assignsSortOrderInInsertionOrder() {
        Course course = new Course("Fair lending", "desc", trainerWithId(1L), T0);

        course.addModule("Intro", "c1", 10);
        course.addModule("Regulation B", "c2", 20);
        course.addModule("Quiz", "c3", 5);

        assertThat(course.getModules())
                .extracting(CourseModule::getSortOrder, CourseModule::getTitle)
                .containsExactly(
                        tuple(1, "Intro"),
                        tuple(2, "Regulation B"),
                        tuple(3, "Quiz"));
        assertThat(course.getModules()).allSatisfy(m -> assertThat(m.getCourse()).isSameAs(course));
    }

    @Test
    void newCourse_startsAsDraft() {
        Course course = new Course("Fair lending", null, trainerWithId(1L), T0);

        assertThat(course.getStatus()).isEqualTo(CourseStatus.DRAFT);
    }

    @Test
    void publish_withModules_setsStatusPublished() {
        Course course = new Course("Fair lending", null, trainerWithId(1L), T0);
        course.addModule("Intro", null, 10);

        course.publish();

        assertThat(course.getStatus()).isEqualTo(CourseStatus.PUBLISHED);
    }

    @Test
    void publish_withoutModules_throwsAndStaysDraft() {
        Course course = new Course("Empty", null, trainerWithId(1L), T0);

        assertThatThrownBy(course::publish)
                .isInstanceOf(BusinessRuleException.class)
                .hasMessageContaining("at least one module");
        assertThat(course.getStatus()).isEqualTo(CourseStatus.DRAFT);
    }

    @Test
    void publish_whenAlreadyPublished_throws() {
        Course course = new Course("Fair lending", null, trainerWithId(1L), T0);
        course.addModule("Intro", null, 10);
        course.publish();

        assertThatThrownBy(course::publish)
                .isInstanceOf(BusinessRuleException.class)
                .hasMessageContaining("already published");
    }

    @Test
    void isOwnedBy_comparesTrainerId() {
        Course course = new Course("Fair lending", null, trainerWithId(7L), T0);

        assertThat(course.isOwnedBy(7L)).isTrue();
        assertThat(course.isOwnedBy(8L)).isFalse();
        // Long boxing trap: equals() is used, so ids above the Integer cache (-128..127) still match.
        assertThat(new Course("x", null, trainerWithId(1000L), T0).isOwnedBy(1000L)).isTrue();
    }

    /** IDs are generated by the database, so outside JPA we set one via reflection. */
    private static AppUser trainerWithId(long id) {
        AppUser trainer = new AppUser("t" + id + "@example.com", "hash", "Trainer " + id, Role.TRAINER, T0);
        ReflectionTestUtils.setField(trainer, "id", id);
        return trainer;
    }
}
