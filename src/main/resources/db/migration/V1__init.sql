create table app_user (
    id            bigint generated by default as identity primary key,
    email         varchar(255) not null unique,
    password_hash varchar(100) not null,
    full_name     varchar(150) not null,
    role          varchar(20)  not null,
    created_at    timestamp with time zone not null
);

create table course (
    id          bigint generated by default as identity primary key,
    title       varchar(200)  not null,
    description varchar(4000),
    status      varchar(20)   not null,
    trainer_id  bigint        not null references app_user (id),
    version     bigint        not null default 0,
    created_at  timestamp with time zone not null
);
create index idx_course_status  on course (status);
create index idx_course_trainer on course (trainer_id);

create table course_module (
    id               bigint generated by default as identity primary key,
    course_id        bigint not null references course (id) on delete cascade,
    title            varchar(200) not null,
    content          varchar(4000),
    sort_order       int not null,
    duration_minutes int not null,
    constraint uq_module_order unique (course_id, sort_order)
);

create table enrollment (
    id           bigint generated by default as identity primary key,
    user_id      bigint not null references app_user (id),
    course_id    bigint not null references course (id),
    status       varchar(20) not null,
    enrolled_at  timestamp with time zone not null,
    completed_at timestamp with time zone,
    constraint uq_enrollment_user_course unique (user_id, course_id)
);
create index idx_enrollment_course on enrollment (course_id);

create table module_completion (
    id            bigint generated by default as identity primary key,
    enrollment_id bigint not null references enrollment (id) on delete cascade,
    module_id     bigint not null references course_module (id),
    completed_at  timestamp with time zone not null,
    constraint uq_completion unique (enrollment_id, module_id)
);